import Constants from 'expo-constants';
import { Link, useFocusEffect } from 'expo-router';
import { useSQLiteContext } from 'expo-sqlite';
import { useCallback, useState } from 'react';
import { Pressable, ScrollView, View } from 'react-native';

import { Button } from '@/components/button';
import { Group, GroupRow } from '@/components/group';
import { ScreenTitle } from '@/components/screen-title';
import { SectionLabel } from '@/components/section-label';
import { ThemedText } from '@/components/themed-text';
import { countLetters, deleteAllLetters } from '@/db/letters';
import { spacing, useColors } from '@/theme';
import { confirmDestructive } from '@/utils/confirm';

export function Settings() {
  const colors = useColors();
  const db = useSQLiteContext();
  const [letterCount, setLetterCount] = useState<number | null>(null);
  const [deleting, setDeleting] = useState(false);
  const [deleteError, setDeleteError] = useState<string | null>(null);

  useFocusEffect(
    useCallback(() => {
      countLetters(db).then(setLetterCount, () => setLetterCount(null));
    }, [db]),
  );

  const deleteAll = async () => {
    const confirmed = await confirmDestructive({
      title: 'Delete all letters?',
      message: 'All saved letters and their explanations are removed from this device. This cannot be undone.',
      confirmLabel: 'Delete all',
    });
    if (!confirmed) {
      return;
    }
    setDeleting(true);
    setDeleteError(null);
    try {
      await deleteAllLetters(db);
      setLetterCount(0);
    } catch (error) {
      setDeleteError(error instanceof Error ? error.message : String(error));
    } finally {
      setDeleting(false);
    }
  };

  return (
    <ScrollView
      contentInsetAdjustmentBehavior="automatic"
      style={{ backgroundColor: colors.paper }}
      contentContainerStyle={{ padding: spacing.md, paddingBottom: spacing.xxl, gap: spacing.lg }}
    >
      <ScreenTitle>Settings</ScreenTitle>

      <View style={{ gap: spacing.sm }}>
        <SectionLabel>Your data</SectionLabel>
        <Group>
          <GroupRow>
            <ThemedText variant="body">
              {letterCount === null
                ? 'Letters are stored only on this device.'
                : letterCount === 1
                  ? '1 letter is stored on this device.'
                  : `${letterCount} letters are stored on this device.`}
            </ThemedText>
            <ThemedText variant="subhead" tone="muted">
              Nothing is uploaded. There is no account, no cloud and no analytics.
            </ThemedText>
          </GroupRow>
        </Group>
        <Button
          title="Delete all letters"
          variant="destructive"
          loading={deleting}
          disabled={letterCount === 0}
          onPress={deleteAll}
        />
        {deleteError ? (
          <ThemedText variant="subhead" tone="deadline" selectable>
            {deleteError}
          </ThemedText>
        ) : null}
      </View>

      <View style={{ gap: spacing.sm }}>
        <SectionLabel>About</SectionLabel>
        <Group>
          <GroupRow>
            <ThemedText variant="headline">Brieflos {Constants.expoConfig?.version ?? ''}</ThemedText>
            <ThemedText variant="subhead" tone="muted">
              Brieflos explains official letters in plain language. Explanations are generated by AI on
              this device and can be wrong. They are not legal advice. For anything important, check the
              original letter or ask the office that sent it.
            </ThemedText>
          </GroupRow>
        </Group>
      </View>

      {__DEV__ ? (
        <View style={{ gap: spacing.sm }}>
          <SectionLabel>Developer</SectionLabel>
          <Group>
            <Link href="/ai-check" asChild>
              <Pressable accessibilityRole="link">
                {({ pressed }) => (
                  <GroupRow style={{ backgroundColor: pressed ? colors.primarySoft : undefined }}>
                    <ThemedText variant="body" tone="primary">
                      On-device AI check
                    </ThemedText>
                    <ThemedText variant="subhead" tone="muted">
                      Run one test explanation on a sample letter.
                    </ThemedText>
                  </GroupRow>
                )}
              </Pressable>
            </Link>
          </Group>
        </View>
      ) : null}
    </ScrollView>
  );
}
